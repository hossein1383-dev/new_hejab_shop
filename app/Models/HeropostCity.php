<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class HeropostCity extends Model
{
    protected $fillable = ['heropost_city_id', 'name', 'province_name', 'province_code'];

    /**
     * ⚠️ این نگاشت دیگر یک حدس نیست — از روی شهرهای واقعی برگشتی هر
     * province_id (با --verify نسخه قبلی) به‌دست آمده. هیروپست از شماره‌گذاری
     * استاندارد/الفبایی استفاده نمی‌کند؛ ترتیب کاملاً داخلی خودشان است.
     * چند مورد (۷، ۹، ۱۷) با شهرهای کوچک‌تر/کمترشناخته‌شده تشخیص داده شدند
     * و اطمینان کمی کمتری دارند — با --verify همین نسخه باید تایید نهایی شوند.
     */
    public const PROVINCE_NAMES = [
        1 => 'تهران', 2 => 'گیلان', 3 => 'آذربایجان شرقی', 4 => 'خوزستان',
        5 => 'فارس', 6 => 'اصفهان', 7 => 'خراسان رضوی', 8 => 'قزوین',
        9 => 'سمنان', 10 => 'قم', 11 => 'مرکزی', 12 => 'زنجان',
        13 => 'مازندران', 14 => 'گلستان', 15 => 'اردبیل', 16 => 'آذربایجان غربی',
        17 => 'همدان', 18 => 'کردستان', 19 => 'کرمانشاه', 20 => 'لرستان',
        21 => 'بوشهر', 22 => 'کرمان', 23 => 'هرمزگان', 24 => 'چهارمحال و بختیاری',
        25 => 'یزد', 26 => 'سیستان و بلوچستان', 27 => 'ایلام', 28 => 'کهگیلویه و بویراحمد',
        29 => 'خراسان شمالی', 30 => 'خراسان جنوبی', 31 => 'البرز',
    ];

    public static function provinceNameFor(?int $provinceId): string
    {
        return self::PROVINCE_NAMES[$provinceId] ?? 'نامشخص';
    }
}
